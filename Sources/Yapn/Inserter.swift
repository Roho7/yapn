import AppKit
import ApplicationServices

struct InsertReport {
    /// `ProcessInfo.systemUptime` when Cmd+V was posted, the same clock as `NSEvent.timestamp`.
    let pastePostedAt: Double
    let snapshotMs: Double
    /// When some process first asked the pasteboard for our text, relative to the paste being posted.
    /// A clipboard manager can be that first reader, so this bounds the target's read from below.
    let firstReadMs: Double?
    let restored: Bool
}

/// Pastes text into the focused app through the clipboard and puts the user's clipboard back afterwards.
@MainActor
final class Inserter {
    /// The snapshot comes back once the pasted text has been read plus `readGrace`, or after
    /// `readTimeout` if nothing reads it (the paste was dropped). A fixed delay would either hand a
    /// slow app the old clipboard or hold the clipboard longer than every fast app needs.
    static let readGrace: Duration = .milliseconds(50)
    static let readTimeout: Duration = .seconds(1)
    private static let vKey: CGKeyCode = 9

    func insert(_ text: String) async -> InsertReport {
        let pasteboard = NSPasteboard.general
        let snapshotStart = ProcessInfo.processInfo.systemUptime
        let snapshot = Self.snapshot(pasteboard)
        let snapshotMs = (ProcessInfo.processInfo.systemUptime - snapshotStart) * 1000

        let provider = TextProvider(text: text)
        let item = NSPasteboardItem()
        item.setDataProvider(provider, forTypes: [.string])
        // nspasteboard.org markers so clipboard managers skip this transient write.
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
        let ourChange = pasteboard.changeCount

        let postedAt = Self.postCommandV()

        let deadline = ContinuousClock.now + Self.readTimeout
        while provider.firstReadAt == nil, ContinuousClock.now < deadline {
            try? await Task.sleep(for: .milliseconds(5))
        }
        try? await Task.sleep(for: Self.readGrace)

        // Someone copied something new in the meantime; theirs wins over our snapshot.
        let restored = pasteboard.changeCount == ourChange
        if restored {
            pasteboard.clearContents()
            if !snapshot.isEmpty { pasteboard.writeObjects(snapshot) }
        }
        return InsertReport(
            pastePostedAt: postedAt,
            snapshotMs: snapshotMs,
            firstReadMs: provider.firstReadAt.map { ($0 - postedAt) * 1000 },
            restored: restored
        )
    }

    static func snapshot(_ pasteboard: NSPasteboard) -> [NSPasteboardItem] {
        (pasteboard.pasteboardItems ?? []).map { item in
            let copy = NSPasteboardItem()
            for type in item.types {
                if let data = item.data(forType: type) { copy.setData(data, forType: type) }
            }
            return copy
        }
    }

    private static func postCommandV() -> Double {
        let source = CGEventSource(stateID: .combinedSessionState)
        let down = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
        return ProcessInfo.processInfo.systemUptime
    }
}

private final class TextProvider: NSObject, NSPasteboardItemDataProvider, @unchecked Sendable {
    let text: String
    var firstReadAt: Double?

    init(text: String) { self.text = text }

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        if firstReadAt == nil { firstReadAt = ProcessInfo.processInfo.systemUptime }
        item.setString(text, forType: type)
    }
}
